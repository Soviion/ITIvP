// Профиль для врача, которого нет в списке выше: внешность и текст подбираются по специальности
export function profileFor(doctor) {
  const known = DOCTOR_PROFILES[doctor.email];
  if (known) return { ...known, experience: new Date().getFullYear() - known.startYear };

  const specialty = doctor.specialty?.name?.toLowerCase() ?? 'врач';
  const female = /(на|ва)$/.test(doctor.middleName ?? '');
  const startYear = 2008 + (doctor.id % 9);
  return {
    look: { gender: female ? 'f' : 'm', style: female ? 'long' : 'short', ...PALETTE[doctor.id % PALETTE.length] },
    position: `Врач-${specialty}`,
    startYear,
    experience: new Date().getFullYear() - startYear,
    quote: 'Внимание к пациенту — основа хорошего лечения.',
    about: `${doctor.firstName} ${doctor.middleName ?? ''} принимает пациентов по профилю «${specialty}»: консультирует, назначает обследования и ведёт лечение до результата.`.replace('  ', ' '),
    education: [{ year: String(startYear - 1), title: 'Медицинский университет', note: 'высшее образование' }],
    career: [{ years: `${startYear} – наст. время`, place: 'Наша клиника', role: `врач-${specialty}` }],
    focus: ['консультации и диагностика', 'назначение лечения', 'наблюдение в динамике'],
    achievements: ['Регулярно повышает квалификацию'],
    languages: ['русский'],
  };
}

// «год»/«года»/«лет»
export const yearsWord = (n) => {
  const rest = n % 100;
  if (rest > 10 && rest < 20) return 'лет';
  return { 1: 'год', 2: 'года', 3: 'года', 4: 'года' }[n % 10] ?? 'лет';
};

